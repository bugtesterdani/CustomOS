void get_offset_address()
{
	uint32_t seg;

	outb(VGA_GC_INDEX, 0x06);
	seg = ((inb(VGA_GC_DATA) >> 2) & 0x03);
	switch(seg)
	{
	case 0:
	case 1:
		offset = (uint8_t*)0xA0000;
		break;
	case 2:
		offset = (uint8_t*)0xB0000;
		break;
	case 3:
		offset = (uint8_t*)0xB8000;
		break;
    default:
        offset = (uint8_t*)0xA0000;
        break;
	}
}

void write_regs(uint8_t *regs)
{
	uint16_t i;
	outb(VGA_MISC_WRITE, *regs);
	regs++;
	for(i = 0; i < VGA_NUM_SEQ_REGS; i++)
	{
		outb(VGA_SEQ_INDEX, i);
		outb(VGA_SEQ_DATA, *regs);
		regs++;
	}
	outb(VGA_CRTC_INDEX_C, 0x03);
	outb(VGA_CRTC_DATA_C, inb(VGA_CRTC_DATA_C) | 0x80);
	outb(VGA_CRTC_INDEX_C, 0x11);
	outb(VGA_CRTC_DATA_C, inb(VGA_CRTC_DATA_C) & ~0x80);
	regs[0x03 + VGA_NUM_SEQ_REGS] |= 0x80;
	regs[0x11 + VGA_NUM_SEQ_REGS] &= ~0x80;
	for(i = 0; i < VGA_NUM_CRTC_REGS; i++)
	{
		outb(VGA_CRTC_INDEX_C, i);
		outb(VGA_CRTC_DATA_C, *regs);
		regs++;
	}
	for(i = 0; i < VGA_NUM_GC_REGS; i++)
	{
		outb(VGA_GC_INDEX, i);
		outb(VGA_GC_DATA, *regs);
		regs++;
	}
	for(i = 0; i < VGA_NUM_AC_REGS; i++)
	{
		inb(VGA_INSTAT_READ);
		outb(VGA_AC_INDEX, i);
		outb(VGA_AC_WRITE, *regs);
		regs++;
	}
	inb(VGA_INSTAT_READ);
	outb(VGA_AC_INDEX, 0x20);
}

void setupmode(uint16_t x, uint16_t y, uint16_t depth)
{
    if (supported_size(x, y, depth) == 0)
    {
        return;
    }

    if (x == 40 && y == 25 && depth == 1)
    {
        write_regs(g_40x25_text);
    }
    else if (x == 40 && y == 50 && depth == 1)
    {
        write_regs(g_40x50_text);
    }
    else if (x == 80 && y == 25 && depth == 1)
    {
        write_regs(g_80x25_text);
    }
    else if (x == 80 && y == 50 && depth == 1)
    {
        write_regs(g_80x50_text);
    }
    else if (x == 90 && y == 30 && depth == 1)
    {
        write_regs(g_90x30_text);
    }
    else if (x == 90 && y == 60 && depth == 1)
    {
        write_regs(g_90x60_text);
    }
    else if (x == 640 && y == 480 && depth == 2)
    {
        write_regs(g_640x480x2);
    }
    else if (x == 320 && y == 200 && depth == 4)
    {
        write_regs(g_320x200x4);
    }
    else if (x == 640 && y == 480 && depth == 16)
    {
        write_regs(g_640x480x16);
    }
    else if (x == 720 && y == 480 && depth == 16)
    {
        write_regs(g_720x480x16);
    }
    else if (x == 320 && y == 200 && depth == 256)
    {
        write_regs(g_320x200x256);
    }
    else
    {
        return;
    }

    get_offset_address();
    Screen_Width = x;
    Screen_Height = y;
    Screen_Depth = depth;
}

uint8_t supported_size(uint16_t x, uint16_t y, uint16_t depth)
{
    if (x == 320 && y == 200 && depth == 256)
    {
        return 1;
    }
    return 0;
}

void putpixel(uint16_t x, uint16_t y, uint8_t color)
{
    if (x < Screen_Width && y < Screen_Height)
    {
        offset[(y * Screen_Width) + x] = color;
    }
}

void DrawLineHorizontal(uint16_t x_start, uint16_t x_size, uint16_t y_start, uint8_t line_thickness, uint8_t color)
{
    for (uint16_t i = 0; i < x_size; i++)
    {
        for (uint16_t j = 0; j < line_thickness; j++)
        {
            putpixel(x_start + i, y_start + j, color);
        }
    }
}

void DrawLineVertical(uint16_t y_start, uint16_t y_size, uint16_t x_start, uint8_t line_thickness, uint8_t color)
{
    for (uint16_t i = 0; i < y_size; i++)
    {
        for (uint16_t j = 0; j < line_thickness; j++)
        {
            putpixel(x_start + j, y_start + i, color);
        }
    }
}

void DrawRectAngle(uint16_t x_start, uint16_t y_start, uint16_t x_size, uint16_t y_size, uint8_t line_thickness_pixel, uint8_t color)
{
    DrawLineHorizontal(x_start, x_size, y_start, line_thickness_pixel, color);
    DrawLineVertical(y_start, y_size, x_start, line_thickness_pixel, color);
    DrawLineHorizontal(x_start, x_size, y_start + y_size, line_thickness_pixel, color);
    DrawLineVertical(y_start, y_size, x_start + x_size, line_thickness_pixel, color);
}

void FillRectangle(uint16_t x_start, uint16_t y_start, uint16_t x_size, uint16_t y_size, uint8_t color)
{
    for (uint16_t i = 0; i < x_size; i++)
    {
        for (uint16_t j = 0; j < y_size; j++)
        {
            putpixel(x_start + i, y_start + j, color);
        }
    }
}
